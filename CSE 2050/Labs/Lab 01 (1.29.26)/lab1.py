def generic_hi(name='world'):
    """Returns a greeting string with an optional name."""
    return f"Hello, {name}!"

def reversing(listA):
    """Returns the provided list in reverse order."""
    return listA[::-1]

def is_multiple(n, m):
    """Checks if n is a multiple of m and returns True or False."""
    return n % m == 0

